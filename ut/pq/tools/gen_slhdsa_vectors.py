"""Generate ut/pq/vectors/slhdsa_kat_vectors.h from NIST ACVP-Server JSON.

usage: python -I gen_slhdsa_vectors.py <acvp_json_root> <out_header>

<acvp_json_root> must contain the (untrusted) downloads
    SLH-DSA-keyGen-FIPS205/internalProjection.json
    SLH-DSA-sigGen-FIPS205/internalProjection.json
    SLH-DSA-sigVer-FIPS205/internalProjection.json
from https://github.com/usnistgov/ACVP-Server/tree/master/gen-val/json-files
(fetched 2026-10-24).  A small subset is emitted:
  * keyGen: one vector per parameter set (all 12 sets).
  * sigGen: for every 'f' set one deterministic internal-interface vector and
    one deterministic external/pure vector (shortest messages); plus one hedged
    (additionalRandomness) vector for SHA2-128f and SHAKE-128f.  The expected
    signature is stored as SHA3-256(signature) and the test recomputes it.
  * sigVer: full signatures for SHA2-128s and SHAKE-128s (one accepted and
    one rejected vector each), stored as hex strings to keep the header small.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pqvec_common as pv  # noqa: E402

PARAMS = {
    "SLH-DSA-SHA2-128s": ("NOXTLS_SLHDSA_SHA2_128S", 16, 7856),
    "SLH-DSA-SHA2-128f": ("NOXTLS_SLHDSA_SHA2_128F", 16, 17088),
    "SLH-DSA-SHA2-192s": ("NOXTLS_SLHDSA_SHA2_192S", 24, 16224),
    "SLH-DSA-SHA2-192f": ("NOXTLS_SLHDSA_SHA2_192F", 24, 35664),
    "SLH-DSA-SHA2-256s": ("NOXTLS_SLHDSA_SHA2_256S", 32, 29792),
    "SLH-DSA-SHA2-256f": ("NOXTLS_SLHDSA_SHA2_256F", 32, 49856),
    "SLH-DSA-SHAKE-128s": ("NOXTLS_SLHDSA_SHAKE_128S", 16, 7856),
    "SLH-DSA-SHAKE-128f": ("NOXTLS_SLHDSA_SHAKE_128F", 16, 17088),
    "SLH-DSA-SHAKE-192s": ("NOXTLS_SLHDSA_SHAKE_192S", 24, 16224),
    "SLH-DSA-SHAKE-192f": ("NOXTLS_SLHDSA_SHAKE_192F", 24, 35664),
    "SLH-DSA-SHAKE-256s": ("NOXTLS_SLHDSA_SHAKE_256S", 32, 29792),
    "SLH-DSA-SHAKE-256f": ("NOXTLS_SLHDSA_SHAKE_256F", 32, 49856),
}

SRC = "https://github.com/usnistgov/ACVP-Server/tree/master/gen-val/json-files"


def param_of(g):
    ps = g.get("parameterSet")
    if ps not in PARAMS:
        raise ValueError("unknown parameter set %r" % ps)
    return ps, PARAMS[ps]


def c_hexstr(name, data, per_line=64):
    name = pv.c_ident(name)
    h = data.hex().upper()
    lines = ['    "%s"' % h[i:i + per_line] for i in range(0, len(h), per_line)]
    return "static const char %s[%d] =\n%s;\n" % (name, len(h) + 1, "\n".join(lines))


def opt_bytes(body, name, data):
    body.append(pv.c_bytes(name, data))
    return name, len(data)


def main():
    root, out = sys.argv[1], sys.argv[2]
    kg = pv.load_json(os.path.join(root, "SLH-DSA-keyGen-FIPS205", "internalProjection.json"))
    sg = pv.load_json(os.path.join(root, "SLH-DSA-sigGen-FIPS205", "internalProjection.json"))
    sv = pv.load_json(os.path.join(root, "SLH-DSA-sigVer-FIPS205", "internalProjection.json"))
    body = []
    prov = [
        "SLH-DSA (FIPS 205) known-answer vectors, subset of the NIST ACVP-Server files",
        "  " + SRC + "/SLH-DSA-{keyGen,sigGen,sigVer}-FIPS205/internalProjection.json",
        "fetched 2026-10-24; generated by ut/pq/tools/gen_slhdsa_vectors.py.",
        "Signatures produced by sigGen vectors are checked via SHA3-256 digests.",
    ]

    # ---- keyGen: first vector of each group --------------------------------
    rows = []
    used = []
    for g in kg["testGroups"]:
        ps, (cname, n, _sl) = param_of(g)
        t = g["tests"][0]
        tc = int(t["tcId"])
        sks = pv.unhex(t["skSeed"], n, "skSeed")
        skp = pv.unhex(t["skPrf"], n, "skPrf")
        pks = pv.unhex(t["pkSeed"], n, "pkSeed")
        pk = pv.unhex(t["pk"], 2 * n, "pk")
        sk = pv.unhex(t["sk"], 4 * n, "sk")
        if sk != sks + skp + pks + pk[n:] or pk[:n] != pks:
            raise ValueError("inconsistent keyGen vector %d" % tc)
        base = "slhdsa_kg_%d" % tc
        body.append(pv.c_bytes(base + "_seeds", sks + skp + pks))
        body.append(pv.c_bytes(base + "_pk", pk))
        rows.append("    { %d, %s, %s_seeds, %s_pk }," % (tc, cname, base, base))
        used.append("keyGen %s tcId %d" % (ps, tc))
    body.append("typedef struct\n{\n    uint32_t tc_id;\n    uint32_t param;\n"
                "    const uint8_t *seeds; /* SK.seed || SK.prf || PK.seed */\n"
                "    const uint8_t *pk;\n} slhdsa_kat_keygen_t;\n\n")
    body.append("static const slhdsa_kat_keygen_t g_slhdsa_kat_keygen[] = {\n%s\n};\n\n" % "\n".join(rows))

    # ---- sigGen --------------------------------------------------------------
    rows = []
    for g in sg["testGroups"]:
        ps, (cname, n, sig_len) = param_of(g)
        if g.get("preHash") == "preHash":
            continue
        det = bool(g["deterministic"])
        iface = g["signatureInterface"]
        fast = ps.endswith("f")
        if not fast:
            continue
        if not det and ps not in ("SLH-DSA-SHA2-128f", "SLH-DSA-SHAKE-128f"):
            continue
        if not det and iface != "external":
            continue
        tests = sorted(g["tests"], key=lambda t: len(t["message"]))
        t = tests[0]
        tc = int(t["tcId"])
        sk = pv.unhex(t["sk"], 4 * n, "sk")
        pk = pv.unhex(t["pk"], 2 * n, "pk")
        if sk[2 * n:] != pk:
            raise ValueError("sk/pk mismatch %d" % tc)
        msg = pv.unhex(t["message"], None, "message")
        ctx = pv.unhex(t.get("context", ""), None, "context") if iface == "external" else b""
        if len(ctx) > 255:
            raise ValueError("context too long")
        sig = pv.unhex(t["signature"], sig_len, "signature")
        base = "slhdsa_sg_%d" % tc
        body.append(pv.c_bytes(base + "_sk", sk))
        body.append(pv.c_bytes(base + "_msg", msg))
        body.append(pv.c_bytes(base + "_ctx", ctx))
        body.append(pv.c_bytes(base + "_sighash", pv.sha3_256(sig)))
        if det:
            rnd = "NULL"
        else:
            body.append(pv.c_bytes(base + "_rnd", pv.unhex(t["additionalRandomness"], n, "addrnd")))
            rnd = base + "_rnd"
        rows.append("    { %d, %s, %dU, %s_sk, %s_msg, %dU, %s_ctx, %dU, %s, %s_sighash }," %
                    (tc, cname, 1 if iface == "external" else 0, base, base, len(msg), base,
                     len(ctx), rnd, base))
        used.append("sigGen %s %s %s tcId %d" % (ps, iface, "det" if det else "hedged", tc))
    body.append("typedef struct\n{\n    uint32_t tc_id;\n    uint32_t param;\n"
                "    uint32_t external; /* 1: pure external M' = 0x00||len(ctx)||ctx||M, 0: internal */\n"
                "    const uint8_t *sk;\n    const uint8_t *msg;\n    uint32_t msg_len;\n"
                "    const uint8_t *ctx;\n    uint32_t ctx_len;\n"
                "    const uint8_t *addrnd; /* NULL: deterministic (opt_rand = PK.seed) */\n"
                "    const uint8_t *sig_sha3_256;\n} slhdsa_kat_siggen_t;\n\n")
    body.append("static const slhdsa_kat_siggen_t g_slhdsa_kat_siggen[] = {\n%s\n};\n\n" % "\n".join(rows))

    # ---- sigVer: SHA2-128s and SHAKE-128s, one pass + one fail each -----------
    rows = []
    for g in sv["testGroups"]:
        ps, (cname, n, sig_len) = param_of(g)
        if ps not in ("SLH-DSA-SHA2-128s", "SLH-DSA-SHAKE-128s") or g.get("preHash") == "preHash":
            continue
        iface = g["signatureInterface"]
        want = {"SLH-DSA-SHA2-128s": "external", "SLH-DSA-SHAKE-128s": "internal"}[ps]
        if iface != want:
            continue
        for passed in (True, False):
            cands = [t for t in g["tests"] if bool(t["testPassed"]) == passed and
                     len(t["signature"]) // 2 == sig_len and
                     (passed or t.get("reason", "").startswith("modified signature"))]
            t = sorted(cands, key=lambda t: len(t["message"]))[0]
            tc = int(t["tcId"])
            pk = pv.unhex(t["pk"], 2 * n, "pk")
            msg = pv.unhex(t["message"], None, "message")
            ctx = pv.unhex(t.get("context", ""), None, "context") if iface == "external" else b""
            sig = pv.unhex(t["signature"], sig_len, "signature")
            base = "slhdsa_sv_%d" % tc
            body.append(pv.c_bytes(base + "_pk", pk))
            body.append(pv.c_bytes(base + "_msg", msg))
            body.append(pv.c_bytes(base + "_ctx", ctx))
            body.append(c_hexstr(base + "_sig_hex", sig))
            rows.append("    { %d, %s, %dU, %s_pk, %s_msg, %dU, %s_ctx, %dU, %s_sig_hex, %dU, %dU }," %
                        (tc, cname, 1 if iface == "external" else 0, base, base, len(msg), base,
                         len(ctx), base, len(sig), 1 if passed else 0))
            used.append("sigVer %s %s tcId %d (%s)" % (ps, iface, tc, t.get("reason", "")))
    body.append("typedef struct\n{\n    uint32_t tc_id;\n    uint32_t param;\n    uint32_t external;\n"
                "    const uint8_t *pk;\n    const uint8_t *msg;\n    uint32_t msg_len;\n"
                "    const uint8_t *ctx;\n    uint32_t ctx_len;\n"
                "    const char *sig_hex;\n    uint32_t sig_len;\n    uint32_t expect_valid;\n"
                "} slhdsa_kat_sigver_t;\n\n")
    body.append("static const slhdsa_kat_sigver_t g_slhdsa_kat_sigver[] = {\n%s\n};\n" % "\n".join(rows))

    prov.append("Vectors used:")
    prov.extend("  " + u for u in used)
    pv.write_header(out, "NOXTLS_SLHDSA_KAT_VECTORS_H_", prov, "".join(body))
    print("wrote", out, os.path.getsize(out), "bytes;", len(used), "vectors")


if __name__ == "__main__":
    main()
