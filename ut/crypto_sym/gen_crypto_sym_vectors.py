def p_hash(hname, secret, seed, n):
    out = b""
    a = seed
    while len(out) < n:
        a = pyhmac.new(secret, a, hname).digest()
        out += pyhmac.new(secret, a + seed, hname).digest()
    return out[:n]


def tls12_prf(hname, secret, label, seed, n):
    return p_hash(hname, secret, label + seed, n)


def tls10_prf(secret, label, seed, n):
    half = (len(secret) + 1) // 2
    s1 = secret[:half]
    s2 = secret[len(secret) - half:]
    return xor(p_hash("md5", s1, label + seed, n), p_hash("sha1", s2, label + seed, n))


def expand_label(hname, secret, label, context, n):
    full = b"tls13 " + label
    info = struct.pack(">H", n) + bytes([len(full)]) + full + bytes([len(context)]) + context
    return hkdf_expand(hname, secret, info, n)


def derive_secret(hname, secret, label, messages):
    return expand_label(hname, secret, label, hashlib.new(hname, messages).digest(), hashlib.new(hname).digest_size)


