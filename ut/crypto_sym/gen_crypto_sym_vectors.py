def hkdf_extract(hname, salt, ikm):
    hl = hashlib.new(hname).digest_size
    if salt is None or len(salt) == 0:
        salt = b"\x00" * hl
    return pyhmac.new(salt, ikm, hname).digest()


def hkdf_expand(hname, prk, info, length):
    out = b""
    t = b""
    i = 1
    while len(out) < length:
        t = pyhmac.new(prk, t + info + bytes([i]), hname).digest()
        out += t
        i += 1
    return out[:length]


