"""Generate the expected-value headers of the ut/crypto_sym regression suite.

Every expected value is computed with an independent implementation
(Python hashlib/hmac, the `cryptography` package, OpenSSL for ARIA, small
pure-Python reference models for MD4, TLS 1.0 PRF and the NoxTLS CTR_DRBG
construction).  Published vectors (FIPS 180-4, FIPS 202, RFC 1320/1321,
RFC 2202, RFC 4231, RFC 5869, RFC 6070, RFC 8448, RFC 8439, SP 800-38A/B/C,
the McGrew-Viega GCM paper, RFC 3394, IEEE 1619, RFC 5794, RFC 3713, RFC 7693)
are asserted against those implementations below, so a typo in a hand-copied
vector aborts generation instead of silently producing a wrong header.

Usage:  python gen_crypto_sym_vectors.py [output_dir]
Requires: Python >= 3.8, cryptography >= 3.0, an `openssl` binary with ARIA
(set OPENSSL=/path/to/openssl if it is not on PATH).
"""

