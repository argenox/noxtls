def md4(msg):
    def f(x, y, z): return (x & y) | (~x & z)
    def g(x, y, z): return (x & y) | (x & z) | (y & z)
    def hh(x, y, z): return x ^ y ^ z
    def rol(v, s): v &= 0xFFFFFFFF; return ((v << s) | (v >> (32 - s))) & 0xFFFFFFFF
    m = bytearray(msg)
    ml = (8 * len(msg)) & 0xFFFFFFFFFFFFFFFF
    m.append(0x80)
    while len(m) % 64 != 56:
        m.append(0)
    m += struct.pack("<Q", ml)
    a, b, c, d = 0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476
    for off in range(0, len(m), 64):
        X = list(struct.unpack("<16I", m[off:off + 64]))
        aa, bb, cc, dd = a, b, c, d
        for i in range(16):
            k = i
            s = [3, 7, 11, 19][i % 4]
            if i % 4 == 0: a = rol(a + f(b, c, d) + X[k], s)
            elif i % 4 == 1: d = rol(d + f(a, b, c) + X[k], s)
            elif i % 4 == 2: c = rol(c + f(d, a, b) + X[k], s)
            else: b = rol(b + f(c, d, a) + X[k], s)
        for i in range(16):
            k = (i % 4) * 4 + i // 4
            s = [3, 5, 9, 13][i % 4]
            if i % 4 == 0: a = rol(a + g(b, c, d) + X[k] + 0x5A827999, s)
            elif i % 4 == 1: d = rol(d + g(a, b, c) + X[k] + 0x5A827999, s)
            elif i % 4 == 2: c = rol(c + g(d, a, b) + X[k] + 0x5A827999, s)
            else: b = rol(b + g(c, d, a) + X[k] + 0x5A827999, s)
        order = [0, 8, 4, 12, 2, 10, 6, 14, 1, 9, 5, 13, 3, 11, 7, 15]
        for i in range(16):
            k = order[i]
            s = [3, 9, 11, 15][i % 4]
            if i % 4 == 0: a = rol(a + hh(b, c, d) + X[k] + 0x6ED9EBA1, s)
            elif i % 4 == 1: d = rol(d + hh(a, b, c) + X[k] + 0x6ED9EBA1, s)
            elif i % 4 == 2: c = rol(c + hh(d, a, b) + X[k] + 0x6ED9EBA1, s)
            else: b = rol(b + hh(c, d, a) + X[k] + 0x6ED9EBA1, s)
        a = (a + aa) & 0xFFFFFFFF
        b = (b + bb) & 0xFFFFFFFF
        c = (c + cc) & 0xFFFFFFFF
        d = (d + dd) & 0xFFFFFFFF
    return struct.pack("<4I", a, b, c, d)


