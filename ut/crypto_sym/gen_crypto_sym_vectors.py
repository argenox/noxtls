def gen_hash():
    check_hash_official()
    h = Header("crypto_sym_hash_vectors.h", "Expected digests for crypto_sym_hash_test.c.")
    h.add("#define CS_HASH_MSG_PRNG_LEN (%dU)\n#define CS_HASH_MSG_PRNG_SEED (0x%08XU)\n\n" % (HASH_MSG_PRNG_LEN, HASH_MSG_PRNG_SEED))
    for name, guard, fn in HASH_ALGS:
        h.add("#if %s\n/* %s: one entry per enum cs_hash_msg value. */\nstatic const char *const k_hash_%s[] = {\n" % (guard, name, name))
        for mname, m in HASH_MSGS:
            h.add('    /* %s */ "%s",\n' % (mname, fn(m).hex()))
        h.add("};\n#endif\n\n")
    # SHAKE: long XOF outputs.
    h.add("#if NOXTLS_FEATURE_SHA3\n")
    h.add("#define CS_SHAKE_LONG_LEN (721U)\n")
    h.add(c_hex("k_shake128_empty_721", hashlib.shake_128(b"").digest(721)))
    h.add(c_hex("k_shake256_a3_721", hashlib.shake_256(b"\xa3" * 200).digest(721)))
    h.add(c_hex("k_shake128_abc_32", hashlib.shake_128(b"abc").digest(32)))
    h.add(c_hex("k_shake256_abc_64", hashlib.shake_256(b"abc").digest(64)))
    prng = cs_fill(HASH_MSG_PRNG_LEN, HASH_MSG_PRNG_SEED)
    h.add(c_hex("k_shake128_prng_300", hashlib.shake_128(prng).digest(300)))
    h.add(c_hex("k_shake256_prng_300", hashlib.shake_256(prng).digest(300)))
    h.add("#endif\n")
    h.write()


