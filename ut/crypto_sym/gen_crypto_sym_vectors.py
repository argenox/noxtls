def cs_fill(n, seed):
    """xorshift32 byte generator; must match cs_fill() in crypto_sym_test_util.h."""
    x = seed & 0xFFFFFFFF
    if x == 0:
        x = 0x9E3779B9
    out = bytearray()
    for _ in range(n):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out.append((x >> 24) & 0xFF)
    return bytes(out)


def c_hex(name, data, static=True):
    h = data.hex()
    if not h:
        return '%sconst char %s[] = "";\n' % ("static " if static else "", name)
    lines = ['    "%s"' % h[i:i + 64] for i in range(0, len(h), 64)]
    return '%sconst char %s[] =\n%s;\n' % ("static " if static else "", name, "\n".join(lines))


def c_str(data):
    """C string literal of hex, split for readability (used inside initialisers)."""
    if data is None:
        return "NULL"
    h = data.hex()
    if len(h) <= 64:
        return '"%s"' % h
    return "\n        ".join('"%s"' % h[i:i + 64] for i in range(0, len(h), 64))


class Header:
    def __init__(self, fname, purpose):
        self.fname = fname
        self.parts = []
        guard = fname.upper().replace(".", "_")
        self.parts.append(
            "/* Generated by gen_crypto_sym_vectors.py - do not edit by hand.\n"
            " * %s\n */\n#ifndef %s\n#define %s\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
            % (purpose, guard, guard))
        self.guard = guard

    def add(self, text):
        self.parts.append(text)

    def write(self):
        self.parts.append("\n#endif /* %s */\n" % self.guard)
        with open(os.path.join(OUT, self.fname), "w", newline="\n") as f:
            f.write("".join(self.parts))


def aes_ecb(key, block):
    e = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    return e.update(block) + e.finalize()


def inc128(b):
    v = (int.from_bytes(b, "big") + 1) % (1 << 128)
    return v.to_bytes(16, "big")


def xor(a, b):
    return bytes(x ^ y for x, y in zip(a, b))


