def openssl_enc(cipher, key, iv, data):
    cmd = [OPENSSL, "enc", "-" + cipher, "-K", key.hex(), "-nopad"]
    if iv is not None:
        cmd += ["-iv", iv.hex()]
    return subprocess.run(cmd, input=data, stdout=subprocess.PIPE, check=True).stdout


def cam_ecb(key, block):
    e = Cipher(algorithms.Camellia(key), modes.ECB()).encryptor()
    return e.update(block) + e.finalize()


def ctr_mode(blockfn, iv, data):
    out = b""
    ctr = iv
    for i in range(0, len(data), 16):
        out += xor(data[i:i + 16], blockfn(ctr))
        ctr = inc128(ctr)
    return out


def gen_aria_camellia():
    h = Header("crypto_sym_aria_camellia_vectors.h", "Expected values for crypto_sym_aria_camellia_test.c.")
    # RFC 5794 appendix A.
    aria_pt = H("00112233445566778899aabbccddeeff")
    aria_exp = ["d718fbd6ab644c739da95f3be6451778", "26449c1805dbe7aa25a468ce263a9e79", "f92bd7c79fb72e2f2b8f80c1972d24fc"]
    for i, kl in enumerate((16, 24, 32)):
        ct = openssl_enc("aria-%d-ecb" % (kl * 8), bytes(range(kl)), None, aria_pt)
        must(ct.hex() == aria_exp[i], "RFC5794 ARIA-%d" % (kl * 8))
    # RFC 3713 appendix A.
    cam_k = H("0123456789abcdeffedcba98765432100011223344556677" "8899aabbccddeeff")
    cam_pt = H("0123456789abcdeffedcba9876543210")
    cam_exp = ["67673138549669730857065648eabe43", "b4993401b3e996f84ee5cee7d79b09b9", "9acc237dff16d76c20ef7c919e3a7509"]
    for i, kl in enumerate((16, 24, 32)):
        must(cam_ecb(cam_k[:kl], cam_pt).hex() == cam_exp[i], "RFC3713 Camellia-%d" % (kl * 8))
    h.add(c_hex("k_aria_block_pt", aria_pt))
    for i, kl in enumerate((16, 24, 32)):
        h.add('static const char k_aria%u_block_ct[] = "%s";\n' % (kl * 8, aria_exp[i]))
    h.add(c_hex("k_cam_block_key", cam_k) + c_hex("k_cam_block_pt", cam_pt))
    for i, kl in enumerate((16, 24, 32)):
        h.add('static const char k_cam%u_block_ct[] = "%s";\n' % (kl * 8, cam_exp[i]))
    # Modes over PRNG data: 64 bytes for ECB/CBC, 61 bytes for CTR/CFB/OFB.
    h.add("#define CS_AC_KEY_SEED (0x41524941U)\n#define CS_AC_IV_SEED (0x49564956U)\n#define CS_AC_MSG_SEED (0x6D736721U)\n")
    key = cs_fill(32, 0x41524941)
    iv = cs_fill(16, 0x49564956)
    blk = cs_fill(64, 0x6D736721)
    st = cs_fill(61, 0x6D736721)
    for kl in (16, 24, 32):
        bits = kl * 8
        k = key[:kl]
        aria = {
            "ecb": openssl_enc("aria-%d-ecb" % bits, k, None, blk),
            "cbc": openssl_enc("aria-%d-cbc" % bits, k, iv, blk),
            "ctr": openssl_enc("aria-%d-ctr" % bits, k, iv, st),
            "cfb": openssl_enc("aria-%d-cfb" % bits, k, iv, st),
            "ofb": openssl_enc("aria-%d-ofb" % bits, k, iv, st),
        }
        cam = {
            "ecb": aes_like(algorithms.Camellia(k), modes.ECB(), blk),
            "cbc": aes_like(algorithms.Camellia(k), modes.CBC(iv), blk),
            "ctr": ctr_mode(lambda b: cam_ecb(k, b), iv, st),
            "cfb": aes_like(algorithms.Camellia(k), modes.CFB(iv), st),
            "ofb": aes_like(algorithms.Camellia(k), modes.OFB(iv), st),
        }
        # openssl agrees with the cryptography-based Camellia CTR model.
        must(openssl_enc("camellia-%d-ctr" % bits, k, iv, st) == cam["ctr"], "Camellia CTR model")
        for m in ("ecb", "cbc", "ctr", "cfb", "ofb"):
            h.add(c_hex("k_aria%u_%s" % (bits, m), aria[m]))
            h.add(c_hex("k_cam%u_%s" % (bits, m), cam[m]))
    h.write()


def aes_like(alg, mode, data):
    e = Cipher(alg, mode).encryptor()
    return e.update(data) + e.finalize()


