#!/usr/bin/env python3
"""Convert NIST CAVP CTR_DRBG response files into crypto_sym_drbg_cavp_vectors.h.

Provenance
----------
Source: NIST CAVP "DRBG Test Vectors" (SP 800-90A), CAVS 14.3, generated
2013-04-02, downloaded 2026-10-24 from
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/drbg/drbgtestvectors.zip
  sha256(drbgtestvectors.zip) = 5f7e5658ebd5b4e6785a7b12fa32333511d2acc2f2d9c5ae1ffa16b699377769
The zip holds drbgvectors_no_reseed.zip, drbgvectors_pr_false.zip and
drbgvectors_pr_true.zip, each with a CTR_DRBG.rsp. Only the AES-128/192/256
"use df" and "no df" sections are used (NoxTLS has no 3KeyTDEA CTR_DRBG).
1440 AES vectors per file, 4320 in total.

Test flows (CAVS DRBGVS):
  no_reseed: Instantiate(EntropyInput, Nonce, PersonalizationString);
             Generate(AdditionalInput); Generate(AdditionalInput) -> ReturnedBits
  pr_false : Instantiate; Reseed(EntropyInputReseed, AdditionalInputReseed);
             Generate(AdditionalInput); Generate(AdditionalInput) -> ReturnedBits
  pr_true  : Instantiate (prediction resistance); Generate(AdditionalInput) with
             EntropyInputPR; Generate(AdditionalInput) with EntropyInputPR -> ReturnedBits

Usage (the downloaded files are untrusted data: keep them in their own directory
and run this script from elsewhere, with python -I):
  python -I gen_drbg_cavp_vectors.py <dir containing no_reseed/ pr_false/ pr_true/> [out.h]

Every vector of the three files is first checked against the independent
SP 800-90A model in sp800_90a_ctr_drbg.py (generation aborts on any mismatch);
then the first COUNT of every (file, AES variant, df / no df, personalization
yes/no, additional input yes/no) group is written: 3 x 3 x 2 x 4 = 72 vectors.
The C test can also run the complete files at run time:
  crypto_sym_drbg_sp800_90a_test <dir>/no_reseed/CTR_DRBG.rsp <dir>/pr_false/CTR_DRBG.rsp ...
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sp800_90a_ctr_drbg as model  # noqa: E402

FILES = (("no_reseed", 0), ("pr_false", 1), ("pr_true", 2))
AES_TYPE = {16: 0, 24: 1, 32: 2}


def c_hex(data):
    h = data.hex()
    if len(h) <= 96:
        return '"%s"' % h
    return "\n        ".join('"%s"' % h[i:i + 96] for i in range(0, len(h), 96))


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    root = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "crypto_sym_drbg_cavp_vectors.h")

    selected = []
    total = 0
    for sub, mode in FILES:
        path = os.path.join(root, sub, "CTR_DRBG.rsp")
        cases = model.parse_rsp(path)
        seen = set()
        for c in cases:
            total += 1
            if model.run_case(c) != c["expected"]:
                raise SystemExit("model mismatch: %s [%s] COUNT=%d" % (path, c["alg"], c["count"]))
            gens = [s for s in c["steps"] if s[0] == "generate"]
            key = (c["alg"], c["use_df"], len(c["pers"]) > 0, len(gens[0][1]) > 0)
            if key in seen:
                continue
            seen.add(key)
            selected.append((sub, mode, c))
        print("%s: %d AES vectors, model OK" % (path, len(cases)))
    print("total %d vectors verified against the SP 800-90A model; %d selected" % (total, len(selected)))

    o = []
    o.append("/* Generated by ut/crypto_sym/tools/gen_drbg_cavp_vectors.py - do not edit by hand.\n"
             " * Subset of the NIST CAVP CTR_DRBG vectors (CAVS 14.3, drbgtestvectors.zip,\n"
             " * sha256 5f7e5658ebd5b4e6785a7b12fa32333511d2acc2f2d9c5ae1ffa16b699377769):\n"
             " * the first COUNT of every AES-128/192/256, use df / no df, personalization\n"
             " * and additional input group of drbgvectors_no_reseed, _pr_false and _pr_true.\n"
             " * Hex strings; \"\" = empty (Null) input.\n"
             " */\n#ifndef CRYPTO_SYM_DRBG_CAVP_VECTORS_H\n#define CRYPTO_SYM_DRBG_CAVP_VECTORS_H\n\n"
             "#include <stdint.h>\n\n"
             "/* mode: 0 = no_reseed, 1 = pr_false (explicit reseed), 2 = pr_true (prediction resistance) */\n"
             "typedef struct {\n"
             "    const char *file; uint32_t count; uint32_t aes_type; uint32_t no_df; uint32_t mode;\n"
             "    uint32_t returned_bits;\n"
             "    const char *entropy; const char *nonce; const char *pers;\n"
             "    const char *entropy_reseed; const char *add_reseed;\n"
             "    const char *add1; const char *entropy_pr1; const char *add2; const char *entropy_pr2;\n"
             "    const char *expected;\n"
             "} cs_drbg_cavp_case_t;\n\n"
             "static const cs_drbg_cavp_case_t k_drbg_cavp[] = {\n")
    for sub, mode, c in selected:
        reseeds = [s for s in c["steps"] if s[0] == "reseed"]
        gens = [s for s in c["steps"] if s[0] == "generate"]
        er, ar = (reseeds[0][1], reseeds[0][2]) if reseeds else (b"", b"")
        e1 = gens[0][2] or b""
        e2 = gens[1][2] or b""
        o.append("    /* %s [%s %s] COUNT = %d */\n" % (sub, c["alg"], "use df" if c["use_df"] else "no df", c["count"]))
        o.append('    { "%s", %uU, %uU, %uU, %uU, %uU,\n' % (
            sub, c["count"], AES_TYPE[c["keylen"]], 0 if c["use_df"] else 1, mode, c["returned_bits_len"]))
        for name, v in (("entropy", c["entropy"]), ("nonce", c["nonce"]), ("pers", c["pers"]),
                        ("entropy_reseed", er), ("add_reseed", ar), ("add1", gens[0][1]),
                        ("entropy_pr1", e1), ("add2", gens[1][1]), ("entropy_pr2", e2)):
            o.append("      /* %s */ %s,\n" % (name, c_hex(v)))
        o.append("      /* expected */ %s },\n" % c_hex(c["expected"]))
    o.append("};\n\n#endif /* CRYPTO_SYM_DRBG_CAVP_VECTORS_H */\n")
    with open(out_path, "w", newline="\n") as f:
        f.write("".join(o))
    print("wrote", os.path.normpath(out_path))


if __name__ == "__main__":
    main()
