"""Generate noxtls-lib/tls/noxtls_abi.h, the link-time ABI fingerprint header.

The preprocessor cannot turn an arithmetic result into a token, so the header
spells each hexadecimal digit of the fingerprint with a 16-way #if chain. This
script writes those chains; edit the knob list here, not in the header.

usage: gen_noxtls_abi_h.py [output]
"""
import os
import sys

# Layout knobs that consumers can set differently from the library; each one
# sizes or shapes tls_context_t, dtls_context_t, tls13_context_t,
# tls12_context_t or the connection memory block. Each is
# visible where noxtls_tls_common.h first ends: noxtls_config.h (with any
# static-memory profile) and noxtls_tls_common.h define them, or the command
# line does. Defaults set by later headers are deliberately absent, so the
# value never depends on include order.
#   (name, kind): "value" uses the number (0 when undefined),
#                 "flag" uses 1 when defined and nonzero, else 0.
