"""Generate noxtls-lib/tls/noxtls_abi.h, the link-time ABI fingerprint header.

The preprocessor cannot turn an arithmetic result into a token, so the header
spells each hexadecimal digit of the fingerprint with a 16-way #if chain. This
script writes those chains; edit the knob list here, not in the header.

usage: gen_noxtls_abi_h.py [output]
"""
import os
import sys

# Layout knobs that consumers can set differently from the library; each one
# sizes or shapes tls_context_t, dtls_context_t, tls13_context_t,
# tls12_context_t or the connection memory block. Each is
# visible where noxtls_tls_common.h first ends: noxtls_config.h (with any
# static-memory profile) and noxtls_tls_common.h define them, or the command
# line does. Defaults set by later headers are deliberately absent, so the
# value never depends on include order.
#   (name, kind): "value" uses the number (0 when undefined),
#                 "flag" uses 1 when defined and nonzero, else 0.
KNOBS = [
    ("TLS_MAX_RECORD_SIZE", "value"),
    ("TLS_MAX_RECV_RECORD_SIZE", "value"),
    ("NOXTLS_TLS_HANDSHAKE_WORKSPACE_SIZE", "value"),
    ("NOXTLS_TLS_MAX_HANDSHAKE_SIZE", "value"),
    ("NOXTLS_TLS_IO_TX_QUEUE_LIMIT", "value"),
    ("NOXTLS_CONFIG_STATIC_MEMORY", "flag"),
    ("NOXTLS_STATIC_RETAIN_PEER_CERT_DER", "flag"),
    ("NOXTLS_STATIC_HS_ARENA_CERT", "value"),
    ("NOXTLS_STATIC_HS_ARENA_PSK", "value"),
    ("NOXTLS_STATIC_HS_ARENA_DTLS_CERT", "value"),
    ("NOXTLS_STATIC_HS_ARENA_DTLS_PSK", "value"),
    ("NOXTLS_STATIC_STEADY_ARENA", "value"),
    ("NOXTLS_STATIC_STEADY_ARENA_DTLS", "value"),
    ("NOXTLS_STATIC_DTLS_FLIGHT_SIZE", "value"),
    ("NOXTLS_STATIC_DTLS_CERT_FLIGHT_SIZE", "value"),
    ("NOXTLS_STATIC_DTLS_POST_HS_FLIGHT_SIZE", "value"),
    ("NOXTLS_STATIC_DTLS_ACK_RANGES", "value"),
    ("NOXTLS_STATIC_TLS_TX_QUEUE_SIZE", "value"),
    ("NOXTLS_STATIC_TRANSCRIPT_BYTES", "value"),
    ("NOXTLS_TLS_RETAIN_PEER_CERT", "flag"),
    ("NOXTLS_TLS13_ACCEPT_TIMING", "flag"),
    ("NOXTLS_TLS_ALGORITHM_FILTER", "flag"),
    ("NOXTLS_TLS12_ENABLE_SHA1_SIGNATURES", "flag"),
    ("NOXTLS_TLS12_ENABLE_LEGACY_CIPHER_SUITES", "flag"),
    ("NOXTLS_FEATURE_TLS10", "flag"),
    ("NOXTLS_FEATURE_TLS11", "flag"),
    ("NOXTLS_FEATURE_TLS12", "flag"),
    ("NOXTLS_FEATURE_TLS13", "flag"),
    ("NOXTLS_FEATURE_DTLS", "flag"),
    ("NOXTLS_FEATURE_DTLS_ECJPAKE", "flag"),
    ("NOXTLS_FEATURE_TLS_CLIENT", "flag"),
    ("NOXTLS_FEATURE_TLS_SERVER", "flag"),
    ("NOXTLS_FEATURE_SHA384", "flag"),
    ("NOXTLS_FEATURE_AES_CCM", "flag"),
    ("NOXTLS_FEATURE_CHACHA20_POLY1305", "flag"),
    ("NOXTLS_FEATURE_ML_KEM", "flag"),
    ("NOXTLS_FEATURE_ML_DSA", "flag"),
    ("NOXTLS_FEATURE_SLH_DSA", "flag"),
    ("NOXTLS_FEATURE_FALCON", "flag"),
]

BANNER = """/*****************************************************************************
* Copyright (c) [2019] - [2026], Argenox Technologies LLC
* All rights reserved.
* SPDX-License-Identifier: GPL-2.0-or-later OR NoxTLS-Commercial
*
*
* This file is part of the NoxTLS Library.
*
* Licensed under the GNU General Public License v2.0 or later,
* or alternatively under a commercial license from
* Argenox Technologies LLC.
*
* See the LICENSE file in the project root for full details.
* CONTACT: info@argenox.com
*
*
* File:    noxtls_abi.h
* Summary: Link-time ABI fingerprint of the TLS context layout
*
* Generated by scripts/gen_noxtls_abi_h.py; edit the script, not this file.
*
*****************************************************************************/
"""

DOC = """/**
 * @file noxtls_abi.h
 * @brief Link-time ABI fingerprint of the TLS context layout.
 *
 * A translation unit that embeds a NoxTLS context must be compiled against the
 * same headers and layout configuration as the library, or the two disagree
 * about field offsets. Every translation unit that includes noxtls_tls_common.h
 * therefore references one symbol, noxtls_abi_<8 hex digits>, and the library
 * defines it (common/noxtls_abi.c). A mismatched consumer fails to link with
 * "undefined reference to noxtls_abi_<digits>".
 *
 * The digits mix three inputs:
 * - NOXTLS_ABI_REVISION, raised when a public context changes outside CMake;
 * - NOXTLS_ABI_LAYOUT_HASH, which the NoxTLS CMake build computes from the
 *   content of the NoxTLS headers and the sizes of tls_context_t,
 *   dtls_context_t, tls13_context_t, tls12_context_t and
 *   noxtls_connection_memory_t under the library's own flags
 *   (cmake/noxtls_abi.cmake), and gives to its targets and their consumers;
 * - the layout knobs below as this translation unit sees them, which catch a
 *   consumer compiled with different record, workspace, feature or
 *   static-memory settings.
 *
 * The library also defines the symbol a consumer without NOXTLS_ABI_LAYOUT_HASH
 * references, so a build outside CMake still links when its knobs match.
 * NOXTLS_ABI_NO_REFERENCE omits the reference (a build-time probe uses it).
 */
"""


def mix_chain(names):
    expr = "NOXTLS_ABI_SEED"
    for name in names:
        expr = "NOXTLS_ABI_MIX(%s, %s)" % (expr, name)
    return expr


def digits(prefix, hash_macro):
    out = []
    for nibble in range(7, -1, -1):
        shift = nibble * 4
        name = "%s%d" % (prefix, nibble)
        for value in range(16):
            keyword = "#if" if value == 0 else "#elif"
            out.append("%s (((%s) >> %dU) & 0xFU) == %dU" % (keyword, hash_macro, shift, value))
            out.append("#define %s %x" % (name, value))
        out.append("#else")
        out.append('#error "NoxTLS ABI fingerprint digit out of range"')
        out.append("#endif")
    return out


def main():
    lines = [BANNER, "#ifndef NOXTLS_ABI_H_", "#define NOXTLS_ABI_H_", "", DOC]
    lines += [
        "/** Revision of the public context layout; raise it with any change to one. */",
        "#define NOXTLS_ABI_REVISION 1U",
        "",
        "/** FNV-1a offset basis and one 32-bit FNV-1a step, evaluated by #if. */",
        "#define NOXTLS_ABI_SEED 2166136261U",
        "#define NOXTLS_ABI_MIX(h, v) (((((h) ^ ((v) & 0xFFFFFFFFU)) * 16777619U)) & 0xFFFFFFFFU)",
        "",
        "/* Each knob as one number; an undefined knob counts as zero. */",
    ]
    knob_macros = []
    for name, kind in KNOBS:
        macro = "NOXTLS_ABI_K_" + name
        knob_macros.append(macro)
        lines.append("#if defined(%s)" % name)
        if kind == "flag":
            lines.append("#if (%s) != 0" % name)
            lines.append("#define %s 1U" % macro)
            lines.append("#else")
            lines.append("#define %s 0U" % macro)
            lines.append("#endif")
        else:
            lines.append("#define %s ((%s) + 1U)" % (macro, name))
        lines.append("#else")
        lines.append("#define %s 0U" % macro)
        lines.append("#endif")
    lines += [
        "",
        "/** Knob fingerprint as this translation unit sees it. */",
        "#define NOXTLS_ABI_KNOBS \\",
        "    (%s)" % mix_chain(["NOXTLS_ABI_REVISION"] + knob_macros),
        "",
        "/** Fingerprint of a consumer without NOXTLS_ABI_LAYOUT_HASH (layout term zero). */",
        "#define NOXTLS_ABI_BASE NOXTLS_ABI_MIX(NOXTLS_ABI_KNOBS, 0U)",
        "#if defined(NOXTLS_ABI_LAYOUT_HASH)",
        "/** Fingerprint with the CMake-computed header and size hash. */",
        "#define NOXTLS_ABI_FULL NOXTLS_ABI_MIX(NOXTLS_ABI_KNOBS, NOXTLS_ABI_LAYOUT_HASH)",
        "#else",
        "#define NOXTLS_ABI_FULL NOXTLS_ABI_BASE",
        "#endif",
        "",
        "/* Hexadecimal digits of both fingerprints, most significant first. */",
    ]
    lines += digits("NOXTLS_ABI_F", "NOXTLS_ABI_FULL")
    lines += digits("NOXTLS_ABI_B", "NOXTLS_ABI_BASE")
    lines += [
        "",
        "#define NOXTLS_ABI_NAME2(a, b, c, d, e, f, g, h) noxtls_abi_##a##b##c##d##e##f##g##h",
        "#define NOXTLS_ABI_NAME(a, b, c, d, e, f, g, h) NOXTLS_ABI_NAME2(a, b, c, d, e, f, g, h)",
        "/** The symbol this translation unit requires. */",
        "#define NOXTLS_ABI_SYMBOL NOXTLS_ABI_NAME(NOXTLS_ABI_F7, NOXTLS_ABI_F6, NOXTLS_ABI_F5, NOXTLS_ABI_F4, \\",
        "    NOXTLS_ABI_F3, NOXTLS_ABI_F2, NOXTLS_ABI_F1, NOXTLS_ABI_F0)",
        "/** The symbol a consumer without NOXTLS_ABI_LAYOUT_HASH requires. */",
        "#define NOXTLS_ABI_BASE_SYMBOL NOXTLS_ABI_NAME(NOXTLS_ABI_B7, NOXTLS_ABI_B6, NOXTLS_ABI_B5, NOXTLS_ABI_B4, \\",
        "    NOXTLS_ABI_B3, NOXTLS_ABI_B2, NOXTLS_ABI_B1, NOXTLS_ABI_B0)",
        "",
        "/* How this translation unit keeps its reference. Linker garbage collection",
        " * (--gc-sections) drops an unreferenced data section and its undefined",
        " * symbol with it, so ELF toolchains with SHF_GNU_RETAIN (GCC 11 and Clang 13",
        " * with binutils 2.36 or later) emit the reference into a retained section.",
        " * The section is a COMDAT group named after the symbol, so a link keeps one",
        " * pointer per distinct fingerprint. Other toolchains use a used static",
        " * pointer, which holds unless the linker collects unreferenced data. */",
        "#if !defined(NOXTLS_ABI_NO_REFERENCE) && !defined(NOXTLS_ABI_RETAINED_SECTION)",
        "#if defined(__ELF__) && defined(__clang__)",
        "#if __clang_major__ >= 13",
        "#define NOXTLS_ABI_RETAINED_SECTION 1",
        "#endif",
        "#elif defined(__ELF__) && defined(__GNUC__)",
        "#if __GNUC__ >= 11",
        "#define NOXTLS_ABI_RETAINED_SECTION 1",
        "#endif",
        "#endif",
        "#endif",
        "#ifndef NOXTLS_ABI_RETAINED_SECTION",
        "#define NOXTLS_ABI_RETAINED_SECTION 0",
        "#endif",
        "",
        "#define NOXTLS_ABI_STR2(x) #x",
        "/** Spell an expanded macro as a string literal. */",
        "#define NOXTLS_ABI_STR(x) NOXTLS_ABI_STR2(x)",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/** Defined by the library for its own layout; see the file comment. */",
        "extern const unsigned char NOXTLS_ABI_SYMBOL;",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "/* This translation unit's reference: an unresolved one names the mismatch. */",
        "#if defined(NOXTLS_ABI_NO_REFERENCE)",
        "/* A build-time probe: no reference. */",
        "#elif NOXTLS_ABI_RETAINED_SECTION",
        r'__asm__(".pushsection .rodata.noxtls_abi_ref,\"aRG\",%progbits," NOXTLS_ABI_STR(NOXTLS_ABI_SYMBOL) "_ref,comdat\n"',
        r'        ".balign 8\n"',
        r'        ".dc.a " NOXTLS_ABI_STR(NOXTLS_ABI_SYMBOL) "\n"',
        r'        ".popsection");',
        "#elif defined(__GNUC__) || defined(__clang__)",
        "__attribute__((used)) static const unsigned char *const noxtls_abi_reference = &NOXTLS_ABI_SYMBOL;",
        "#else",
        "static const unsigned char *const noxtls_abi_reference = &NOXTLS_ABI_SYMBOL;",
        "#endif",
        "",
        "#endif /* NOXTLS_ABI_H_ */",
        "",
    ]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "noxtls-lib", "tls", "noxtls_abi.h")
    with open(target, "w", newline="\n") as handle:
        handle.write("\n".join(lines))


if __name__ == "__main__":
    main()
