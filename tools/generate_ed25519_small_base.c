/** @file generate_ed25519_small_base.c
 * @brief Host-only reproducible generator; no external table source.
 */
#include <stdio.h>
#if defined(NOXTLS_ED25519_READONLY_SMALL_BASE) && NOXTLS_ED25519_READONLY_SMALL_BASE
#error "Generate from mutable in-house arithmetic, not an existing constant table"
#endif
#define NOXTLS_ED25519_SMALL_BASE 1
#include "../noxtls-lib/pkc/ed25519/noxtls_ed25519_ge.c"

/** @brief Print exact native signed limbs.
 * @param[in] field Field produced by the in-house arithmetic.
 */
static void table_print_field(const fe25519_native_t *field)
{
    uint32_t i;
    (void)fputs("{{", stdout);
    for(i = 0U; i < NOXTLS_ED25519_FE_LIMBS; i++) {
        if(i != 0U) {
            (void)fputc(',', stdout);
        }

        (void)printf("%ld", (long)field->v[i]);
    }

    (void)fputs("}}", stdout);
}

/** @brief Generate compact fixed-base and verify-odd entries.
 * @return Zero after successful generation, one on failure.
 */
int main(void)
{
    uint32_t i;
    if(ge25519_base_table_small_init() != NOXTLS_RETURN_SUCCESS ||
       ge25519_base_odd_init() != NOXTLS_RETURN_SUCCESS) {
        return 1;
    }

    (void)fputs("/* Copyright (c) 2026 Argenox Technologies LLC. All rights reserved. */\n"
        "/* SPDX-License-Identifier: GPL-2.0-or-later OR NoxTLS-Commercial */\n"
        "/* Generated by tools/generate_ed25519_small_base.c. Do not edit. */\n"
        "/* Native X,Y,Z,T multiples [0,15]B; odd Duif multiples [1,31]B. */\n"
        "static const ge25519_n_t g_base_table_small[NOXTLS_ED25519_SCALAR_TABLE_ENTRIES] = {\n", stdout);
    for(i = 0U; i < NOXTLS_ED25519_SCALAR_TABLE_ENTRIES; i++) {
        (void)fputs("    {", stdout);
        table_print_field(&g_base_table_small[i].X);
        (void)fputc(',', stdout);
        table_print_field(&g_base_table_small[i].Y);
        (void)fputc(',', stdout);
        table_print_field(&g_base_table_small[i].Z);
        (void)fputc(',', stdout);
        table_print_field(&g_base_table_small[i].T);
        (void)fputs(i + 1U < NOXTLS_ED25519_SCALAR_TABLE_ENTRIES ? "},\n" : "}\n", stdout);
    }

    (void)fputs("};\nstatic const ge25519_precomp_t g_base_odd[NOXTLS_ED25519_SLIDE_ODD_COUNT] = {\n", stdout);
    for(i = 0U; i < NOXTLS_ED25519_SLIDE_ODD_COUNT; i++) {
        (void)fputs("    {", stdout);
        table_print_field(&g_base_odd[i].yplusx);
        (void)fputc(',', stdout);
        table_print_field(&g_base_odd[i].yminusx);
        (void)fputc(',', stdout);
        table_print_field(&g_base_odd[i].xy2d);
        (void)fputs(i + 1U < NOXTLS_ED25519_SLIDE_ODD_COUNT ? "},\n" : "}\n", stdout);
    }

    (void)fputs("};\n", stdout);
    return ferror(stdout) != 0 ? 1 : 0;
}
