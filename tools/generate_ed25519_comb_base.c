/** @file generate_ed25519_comb_base.c
 * @brief Host-only reproducible generator for noxtls_ed25519_comb_readonly.inc.
 *
 * Builds the signed multi-comb fixed-base table and the sliding-verify odd-B
 * table with the lazy (RAM) table builders of noxtls_ed25519_ge.c and prints
 * the exact native signed limbs. No external table source is used.
 */
#include <stdio.h>
#if defined(NOXTLS_ED25519_SMALL_BASE) || defined(NOXTLS_ED25519_DUMP_BASE)
#error "The comb generator needs the default comb geometry"
#endif
#if defined(NOXTLS_ED25519_READONLY_COMB) && NOXTLS_ED25519_READONLY_COMB
#error "Generate from mutable in-house arithmetic, not an existing constant table"
#endif
#define NOXTLS_ED25519_READONLY_COMB 0
#include "../noxtls-lib/pkc/ed25519/noxtls_ed25519_ge.c"

/** @brief Print exact native signed limbs.
 * @param[in] field Field produced by the in-house arithmetic.
 */
static void table_print_field(const fe25519_native_t *field)
{
    uint32_t i;
    (void)fputs("{{", stdout);
    for(i = 0U; i < NOXTLS_ED25519_FE_LIMBS; i++) {
        if(i != 0U) {
            (void)fputc(',', stdout);
        }

        (void)printf("%ld", (long)field->v[i]);
    }

    (void)fputs("}}", stdout);
}

/** @brief Print one Duif precomp entry.
 * @param[in] entry Entry produced by the in-house arithmetic.
 * @param[in] last Non-zero for the last entry of an initializer list.
 */
static void table_print_precomp(const ge25519_precomp_t *entry, int last)
{
    (void)fputs("    {", stdout);
    table_print_field(&entry->yplusx);
    (void)fputc(',', stdout);
    table_print_field(&entry->yminusx);
    (void)fputc(',', stdout);
    table_print_field(&entry->xy2d);
    (void)fputs(last != 0 ? "}\n" : "},\n", stdout);
}

/** @brief Generate comb fixed-base and verify-odd entries.
 * @return Zero after successful generation, one on failure.
 */
int main(void)
{
    uint32_t block;
    uint32_t i;
    if(ge25519_comb_init() != NOXTLS_RETURN_SUCCESS ||
       ge25519_base_odd_init() != NOXTLS_RETURN_SUCCESS) {
        return 1;
    }

    (void)fputs("/* Copyright (c) 2026 Argenox Technologies LLC. All rights reserved. */\n"
        "/* SPDX-License-Identifier: GPL-2.0-or-later OR NoxTLS-Commercial */\n"
        "/* Generated by tools/generate_ed25519_comb_base.c. Do not edit. */\n"
        "/* Signed multi-comb (8,4,8) Duif entries per block; odd Duif multiples [1,31]B. */\n"
        "static const ge25519_precomp_t g_base_comb[NOXTLS_ED25519_COMB_BLOCKS][NOXTLS_ED25519_COMB_POINTS] = {\n",
        stdout);
    for(block = 0U; block < NOXTLS_ED25519_COMB_BLOCKS; block++) {
        (void)fputs("  {\n", stdout);
        for(i = 0U; i < NOXTLS_ED25519_COMB_POINTS; i++) {
            table_print_precomp(&g_base_comb[block][i], (i + 1U) == NOXTLS_ED25519_COMB_POINTS);
        }

        (void)fputs((block + 1U) < NOXTLS_ED25519_COMB_BLOCKS ? "  },\n" : "  }\n", stdout);
    }

    (void)fputs("};\nstatic const ge25519_precomp_t g_base_odd[NOXTLS_ED25519_SLIDE_ODD_COUNT] = {\n", stdout);
    for(i = 0U; i < NOXTLS_ED25519_SLIDE_ODD_COUNT; i++) {
        table_print_precomp(&g_base_odd[i], (i + 1U) == NOXTLS_ED25519_SLIDE_ODD_COUNT);
    }

    (void)fputs("};\n", stdout);
    return ferror(stdout) != 0 ? 1 : 0;
}
