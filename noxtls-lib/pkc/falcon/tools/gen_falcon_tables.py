"""Generate noxtls_falcon_tables.inc (constant tables for the Falcon backend).

usage: python -I gen_falcon_tables.py <out.inc>

Tables (all derived from first principles, no external input):
  * falcon_gm_tab[2048]   complex roots exp(i*pi*rev10(k)/1024), k = 0..1023,
                          interleaved (re, im) and correctly rounded to binary64
                          (computed with 60-digit decimal arithmetic).  This is
                          the root ordering used by the Falcon FFT representation
                          (bit-reversed evaluation points of x^n + 1).
  * falcon_ntt_zetas[1024] / falcon_ntt_izetas[1024]
                          psi^rev10(k) and psi^-rev10(k) mod q = 12289, where psi
                          is the primitive 2048-th root of unity 11^6 mod q (11 generates Z_q^*).
  * falcon_keygen_cdt_512 / falcon_keygen_cdt_1024
                          floor(2^63 * Pr[|X| > k]) for X ~ D_{Z,sigma_fg},
                          sigma_fg = 1.17 * sqrt(q / (2n)) (Falcon spec NTRUGen).
"""

import sys
from decimal import Decimal, getcontext

getcontext().prec = 80
Q = 12289


def dec_pi():
    # Chudnovsky-free: Machin formula with Decimal.
    def arctan_inv(x):
        x = Decimal(x)
        total = Decimal(0)
        term = 1 / x
        x2 = x * x
        k = 0
        while True:
            t = term / (2 * k + 1)
            if t == 0 or abs(t) < Decimal(10) ** -78:
                break
            total += t if k % 2 == 0 else -t
            term /= x2
            k += 1
        return total
    return 4 * (4 * arctan_inv(5) - arctan_inv(239))


PI = dec_pi()


def dec_cos_sin(a):
    # Taylor series; |a| <= pi.
    c = Decimal(0)
    s = Decimal(0)
    term = Decimal(1)
    k = 0
    while True:
        if k % 4 == 0:
            c += term
        elif k % 4 == 1:
            s += term
        elif k % 4 == 2:
            c -= term
        else:
            s -= term
        k += 1
        term = term * a / k
        if abs(term) < Decimal(10) ** -78:
            break
    return c, s


def rev(x, bits):
    r = 0
    for _ in range(bits):
        r = (r << 1) | (x & 1)
        x >>= 1
    return r


def to_double(d):
    if abs(d) < Decimal(10) ** -60:
        return 0.0
    return float(d)


def gm_table():
    vals = []
    for k in range(1024):
        if k == 0:
            vals += [0.0, 0.0]
            continue
        c, s = dec_cos_sin(PI * rev(k, 10) / 1024)
        vals += [to_double(c), to_double(s)]
    return vals


def ntt_tables():
    psi = pow(11, (Q - 1) // 2048, Q)
    assert pow(psi, 1024, Q) == Q - 1
    z = [pow(psi, rev(k, 10), Q) for k in range(1024)]
    iz = [pow(psi, (2048 - rev(k, 10)) % 2048, Q) for k in range(1024)]
    return z, iz


def dexp(x):
    # exp(x) for Decimal x <= 0 via range reduction.
    n = 0
    while x < -1:
        x /= 2
        n += 1
    total = Decimal(1)
    term = Decimal(1)
    k = 1
    while True:
        term = term * x / k
        if abs(term) < Decimal(10) ** -78:
            break
        total += term
        k += 1
    for _ in range(n):
        total *= total
    return total


def cdt(n):
    sigma = Decimal("1.17") * (Decimal(Q) / Decimal(2 * n)).sqrt()
    two_s2 = 2 * sigma * sigma
    probs = [dexp(-Decimal(k * k) / two_s2) for k in range(0, 200)]
    norm = probs[0] + 2 * sum(probs[1:])
    # Pr[|X| > k]
    tail = []
    acc = Decimal(1) - probs[0] / norm
    k = 0
    while True:
        v = int(acc * (Decimal(2) ** 63))
        if v == 0:
            break
        tail.append(v)
        k += 1
        acc -= 2 * probs[k] / norm
    return sigma, tail


def emit(out):
    gm = gm_table()
    z, iz = ntt_tables()
    lines = []
    lines.append("/* GENERATED by noxtls-lib/pkc/falcon/tools/gen_falcon_tables.py - do not edit. */\n")
    lines.append("/* clang-format off */\n\n")
    lines.append("/** FFT roots exp(i*pi*rev10(k)/1024), interleaved (re, im); entry 0 unused. */\n")
    lines.append("static const double falcon_gm_tab[2048] = {\n")
    for i in range(0, 2048, 2):
        lines.append("    %s, %s,\n" % (repr(gm[i]), repr(gm[i + 1])))
    lines.append("};\n\n")
    for name, tab, doc in (("falcon_ntt_zetas", z, "psi^rev10(k) mod q"),
                           ("falcon_ntt_izetas", iz, "psi^-rev10(k) mod q")):
        lines.append("/** %s (psi = 11^6 mod 12289). */\n" % doc)
        lines.append("static const uint16_t %s[1024] = {\n" % name)
        for i in range(0, 1024, 16):
            lines.append("    " + ", ".join("%5uU" % v for v in tab[i:i + 16]) + ",\n")
        lines.append("};\n\n")
    for n in (512, 1024):
        sigma, tail = cdt(n)
        lines.append("/** floor(2^63 * Pr[|X| > k]), X ~ D_{Z,sigma}, sigma = %s (n = %d). */\n"
                     % (str(sigma)[:12], n))
        lines.append("static const uint64_t falcon_keygen_cdt_%d[%d] = {\n" % (n, len(tail)))
        for v in tail:
            lines.append("    0x%016XU,\n" % v)
        lines.append("};\n\n")
    lines.append("/* clang-format on */\n")
    with open(out, "w", newline="\n") as f:
        f.write("".join(lines))


if __name__ == "__main__":
    emit(sys.argv[1])
